#!/usr/bin/env bash

sentinal_install_die() {
  echo "sentinal installer: $*" >&2
  exit 1
}

sentinal_install_platform() {
  local value="${SENTINAL_INSTALL_PLATFORM:-}"
  if [[ -z "$value" ]]; then
    case "$(uname -s)" in
      Darwin) value=macos ;;
      Linux) value=linux ;;
      *) value="$(uname -s | tr '[:upper:]' '[:lower:]')" ;;
    esac
  fi
  case "$value" in
    macos|linux) printf '%s\n' "$value" ;;
    *) sentinal_install_die "unsupported operating system '$value'; expected macos or linux" ;;
  esac
}

sentinal_require_safe_path() {
  local name="$1" value="$2"
  [[ "$value" == /* ]] || sentinal_install_die "$name path '$value' must be absolute"
  case "$value" in
    /|"$HOME"|*/../*|*/..|*/./*) sentinal_install_die "refusing unsafe $name path '$value'" ;;
  esac
}

sentinal_canonical_existing_path() {
  local value="$1" parent base
  parent="$(dirname "$value")"
  base="$(basename "$value")"
  [[ -d "$parent" ]] || sentinal_install_die "cannot resolve path '$value': parent does not exist"
  printf '%s/%s\n' "$(cd "$parent" && pwd -P)" "$base"
}

sentinal_stat_owner_mode() {
  local path="$1"
  if stat -f '%u %Lp' "$path" 2>/dev/null; then
    return
  fi
  stat -c '%u %a' "$path"
}

sentinal_validate_source_binary() {
  local path="$1" owner mode
  [[ -f "$path" && -x "$path" && ! -L "$path" ]] || sentinal_install_die "missing executable source binary '$path'"
  read -r owner mode <<<"$(sentinal_stat_owner_mode "$path")"
  if [[ "$owner" != "$(id -u)" ]] || (((8#$mode & 022) != 0)); then
    sentinal_install_die "unsafe source binary '$path': it must be owned by uid $(id -u) and not group/world writable"
  fi
}

sentinal_atomic_install() {
  local source="$1" destination="$2" temporary
  temporary="$destination.tmp.$$"
  if ! cp "$source" "$temporary" || ! chmod 755 "$temporary" || ! mv -f "$temporary" "$destination"; then
    rm -f -- "$temporary"
    return 1
  fi
}

sentinal_xml_escape() {
  local value="$1"
  value="${value//&/&amp;}"
  value="${value//</&lt;}"
  value="${value//>/&gt;}"
  printf '%s' "$value"
}

sentinal_systemd_escape() {
  local value="$1"
  value="${value//\\/\\\\}"
  value="${value//\"/\\\"}"
  value="${value//%/%%}"
  printf '%s' "$value"
}

sentinal_render_launchd() {
  local daemon_bin="$1" config_file="$2" stdout_file="$3" stderr_file="$4"
  cat <<EOF
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<!-- Generated by install-worker.sh. Contains paths only; credentials remain in owner-only files. -->
<plist version="1.0">
<dict>
  <key>Label</key>
  <string>dev.sentinal.sentinald</string>
  <key>ProgramArguments</key>
  <array>
    <string>$(sentinal_xml_escape "$daemon_bin")</string>
  </array>
  <key>EnvironmentVariables</key>
  <dict>
    <key>TA_CONFIG</key>
    <string>$(sentinal_xml_escape "$config_file")</string>
  </dict>
  <key>RunAtLoad</key>
  <true/>
  <key>KeepAlive</key>
  <true/>
  <key>StandardOutPath</key>
  <string>$(sentinal_xml_escape "$stdout_file")</string>
  <key>StandardErrorPath</key>
  <string>$(sentinal_xml_escape "$stderr_file")</string>
</dict>
</plist>
EOF
}

sentinal_render_systemd() {
  local daemon_bin config_file
  daemon_bin="$(sentinal_systemd_escape "$1")"
  config_file="$(sentinal_systemd_escape "$2")"
  cat <<EOF
[Unit]
Description=Sentinal daemon (persistent, observable terminal Sessions)
After=network.target
Conflicts=tad.service

[Service]
Type=simple
Environment="TA_CONFIG=$config_file"
ExecStart="$daemon_bin"
Restart=on-failure
RestartSec=2

[Install]
WantedBy=default.target
EOF
}

sentinal_service_action() {
  if [[ -n "${SENTINAL_SERVICE_TEST_LOG:-}" ]]; then
    printf '%s\n' "$*" >>"$SENTINAL_SERVICE_TEST_LOG"
    return
  fi
  "$@"
}

sentinal_enable_service() {
  local platform="$1" service_file="$2"
  if [[ "$platform" == macos ]]; then
    sentinal_service_action launchctl bootout "gui/$(id -u)/dev.sentinal.sentinald" 2>/dev/null || true
    sentinal_service_action launchctl bootstrap "gui/$(id -u)" "$service_file"
    sentinal_service_action launchctl enable "gui/$(id -u)/dev.sentinal.sentinald"
    sentinal_service_action launchctl kickstart -k "gui/$(id -u)/dev.sentinal.sentinald"
  else
    sentinal_service_action systemctl --user daemon-reload
    sentinal_service_action systemctl --user enable sentinald.service
    sentinal_service_action systemctl --user restart sentinald.service
  fi
}

sentinal_disable_service() {
  local platform="$1"
  if [[ "$platform" == macos ]]; then
    sentinal_service_action launchctl bootout "gui/$(id -u)/dev.sentinal.sentinald" 2>/dev/null || true
  else
    sentinal_service_action systemctl --user disable --now sentinald.service 2>/dev/null || true
  fi
}

sentinal_reload_service_manager() {
  local platform="$1"
  if [[ "$platform" == linux ]]; then
    sentinal_service_action systemctl --user daemon-reload
  fi
}
