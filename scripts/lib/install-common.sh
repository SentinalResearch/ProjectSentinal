#!/usr/bin/env bash

sentinal_install_die() {
  echo "sentinal installer: $*" >&2
  exit 1
}

sentinal_release_field() {
  local file="$1" field="$2"
  [[ -f "$file" && ! -L "$file" ]] || return 1
  sed -n "s/.*\"$field\"[[:space:]]*:[[:space:]]*\"\([^\"]*\)\".*/\1/p" "$file" | head -n 1
}

sentinal_valid_release_version() {
  local value="$1" major minor patch extra part
  IFS=. read -r major minor patch extra <<<"$value"
  [[ -z "${extra:-}" && -n "${major:-}" && -n "${minor:-}" && -n "${patch:-}" ]] || return 1
  for part in "$major" "$minor" "$patch"; do
    [[ "$part" =~ ^(0|[1-9][0-9]{0,8})$ ]] || return 1
  done
}

sentinal_compare_release_versions() {
  local left="$1" right="$2" left_parts right_parts index left_value right_value
  IFS=. read -r -a left_parts <<<"$left"
  IFS=. read -r -a right_parts <<<"$right"
  for index in 0 1 2; do
    left_value=$((10#${left_parts[$index]}))
    right_value=$((10#${right_parts[$index]}))
    if ((left_value < right_value)); then printf '%s\n' -1; return; fi
    if ((left_value > right_value)); then printf '%s\n' 1; return; fi
  done
  printf '%s\n' 0
}

sentinal_validate_control_url() {
  local value="$1" host
  host="${value#https://}"
  [[ "$value" == https://* && "$host" == *.ts.net ]] || sentinal_install_die "control URL '$value' must be one HTTPS .ts.net origin"
  case "$host" in
    *'/'*|*'?'*|*'#'*|*'@'*|*':'*) sentinal_install_die "control URL '$value' must not contain a path, port, query, fragment, or credentials" ;;
  esac
  [[ "$host" =~ ^[A-Za-z0-9.-]+$ ]] || sentinal_install_die "control URL '$value' contains invalid hostname characters"
}

sentinal_install_platform() {
  local value="${SENTINAL_INSTALL_PLATFORM:-}"
  if [[ -z "$value" ]]; then
    case "$(uname -s)" in
      Darwin) value=macos ;;
      Linux) value=linux ;;
      *) value="$(uname -s | tr '[:upper:]' '[:lower:]')" ;;
    esac
  fi
  case "$value" in
    macos|linux) printf '%s\n' "$value" ;;
    *) sentinal_install_die "unsupported operating system '$value'; expected macos or linux" ;;
  esac
}

sentinal_require_safe_path() {
  local name="$1" value="$2"
  [[ "$value" == /* ]] || sentinal_install_die "$name path '$value' must be absolute"
  case "$value" in
    /|"$HOME"|*/../*|*/..|*/./*) sentinal_install_die "refusing unsafe $name path '$value'" ;;
  esac
}

sentinal_canonical_existing_path() {
  local value="$1" parent base
  parent="$(dirname "$value")"
  base="$(basename "$value")"
  [[ -d "$parent" ]] || sentinal_install_die "cannot resolve path '$value': parent does not exist"
  printf '%s/%s\n' "$(cd "$parent" && pwd -P)" "$base"
}

sentinal_stat_owner_mode() {
  local path="$1"
  if stat -f '%u %Lp' "$path" >/dev/null 2>&1; then
    stat -f '%u %Lp' "$path"
  else
    stat -c '%u %a' "$path"
  fi
}

sentinal_validate_source_binary() {
  local path="$1" owner mode
  [[ -f "$path" && -x "$path" && ! -L "$path" ]] || sentinal_install_die "missing executable source binary '$path'"
  read -r owner mode <<<"$(sentinal_stat_owner_mode "$path")"
  if [[ "$owner" != "$(id -u)" ]] || (((8#$mode & 022) != 0)); then
    sentinal_install_die "unsafe source binary '$path': it must be owned by uid $(id -u) and not group/world writable"
  fi
}

sentinal_atomic_install() {
  local source="$1" destination="$2" temporary
  temporary="$destination.tmp.$$"
  if ! cp "$source" "$temporary" || ! chmod 755 "$temporary" || ! mv -f "$temporary" "$destination"; then
    rm -f -- "$temporary"
    return 1
  fi
}

sentinal_xml_escape() {
  local value="$1"
  value="${value//&/&amp;}"
  value="${value//</&lt;}"
  value="${value//>/&gt;}"
  printf '%s' "$value"
}

sentinal_systemd_escape() {
  local value="$1"
  value="${value//\\/\\\\}"
  value="${value//\"/\\\"}"
  value="${value//%/%%}"
  printf '%s' "$value"
}

sentinal_render_launchd() {
  local daemon_bin="$1" config_file="$2" stdout_file="$3" stderr_file="$4"
  cat <<EOF
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<!-- Generated by install-worker.sh. Contains paths only; credentials remain in owner-only files. -->
<plist version="1.0">
<dict>
  <key>Label</key>
  <string>dev.sentinal.sentinald</string>
  <key>ProgramArguments</key>
  <array>
    <string>$(sentinal_xml_escape "$daemon_bin")</string>
  </array>
  <key>EnvironmentVariables</key>
  <dict>
    <key>TA_CONFIG</key>
    <string>$(sentinal_xml_escape "$config_file")</string>
  </dict>
  <key>RunAtLoad</key>
  <true/>
  <key>KeepAlive</key>
  <true/>
  <key>StandardOutPath</key>
  <string>$(sentinal_xml_escape "$stdout_file")</string>
  <key>StandardErrorPath</key>
  <string>$(sentinal_xml_escape "$stderr_file")</string>
</dict>
</plist>
EOF
}

sentinal_render_systemd() {
  local daemon_bin config_file
  daemon_bin="$(sentinal_systemd_escape "$1")"
  config_file="$(sentinal_systemd_escape "$2")"
  cat <<EOF
[Unit]
Description=Sentinal daemon (persistent, observable terminal Sessions)
After=network.target
Conflicts=tad.service

[Service]
Type=simple
Environment="TA_CONFIG=$config_file"
ExecStart="$daemon_bin"
Restart=on-failure
RestartSec=2

[Install]
WantedBy=default.target
EOF
}

sentinal_service_action() {
  if [[ -n "${SENTINAL_SERVICE_TEST_LOG:-}" ]]; then
    printf '%s\n' "$*" >>"$SENTINAL_SERVICE_TEST_LOG"
    if [[ -n "${SENTINAL_SERVICE_TEST_FAIL_ON:-}" && "$*" == *"$SENTINAL_SERVICE_TEST_FAIL_ON"* ]]; then
      return 1
    fi
    return
  fi
  "$@"
}

sentinal_wait_for_launchd_bootout() {
  local service="$1" attempt
  if [[ -n "${SENTINAL_SERVICE_TEST_LOG:-}" ]]; then
    printf 'wait launchd bootout %s\n' "$service" >>"$SENTINAL_SERVICE_TEST_LOG"
    return
  fi
  for attempt in {1..20}; do
    if ! launchctl print "$service" >/dev/null 2>&1; then
      return
    fi
    sleep 0.05
  done
  echo "sentinal installer: launchd service '$service' did not finish stopping" >&2
  return 1
}

sentinal_enable_service() {
  local platform="$1" service_file="$2"
  if [[ "$platform" == macos ]]; then
    local service="gui/$(id -u)/dev.sentinal.sentinald"
    sentinal_service_action launchctl bootout "$service" 2>/dev/null || true
    sentinal_wait_for_launchd_bootout "$service" || return
    sentinal_service_action launchctl bootstrap "gui/$(id -u)" "$service_file" || return
    sentinal_service_action launchctl enable "$service" || return
    sentinal_service_action launchctl kickstart -k "$service" || return
  else
    sentinal_service_action systemctl --user daemon-reload || return
    sentinal_service_action systemctl --user enable sentinald.service || return
    sentinal_service_action systemctl --user restart sentinald.service || return
  fi
}

sentinal_disable_service() {
  local platform="$1"
  if [[ "$platform" == macos ]]; then
    sentinal_service_action launchctl bootout "gui/$(id -u)/dev.sentinal.sentinald" 2>/dev/null || true
  else
    sentinal_service_action systemctl --user disable --now sentinald.service 2>/dev/null || true
  fi
}

sentinal_reload_service_manager() {
  local platform="$1"
  if [[ "$platform" == linux ]]; then
    sentinal_service_action systemctl --user daemon-reload
  fi
}
