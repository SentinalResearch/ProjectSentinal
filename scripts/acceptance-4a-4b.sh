#!/usr/bin/env bash
# Acceptance checklist for Milestones 4.A (routing) and 4.B (V1 demo).
# Run on EACH Machine (control, Worker A, Worker B). Paste output back.
# No secrets are printed: tokens, pairing codes, and credentials are never echoed.
set -euo pipefail

echo "=== MACHINE IDENTITY ==="
echo "hostname: $(hostname)"
if command -v sw_vers >/dev/null 2>&1; then sw_vers; else cat /etc/os-release 2>/dev/null | head -3; fi
echo "uname: $(uname -a)"
echo "tailscale version: $(tailscale version 2>/dev/null | head -1 || echo 'not installed')"
echo "tailscale ip: $(tailscale ip -4 2>/dev/null || echo 'none')"
echo "sentinal version: $(sentinal --version 2>/dev/null || echo 'not installed')"
echo ""
echo "=== CONNECTION STATUS ==="
sentinal connection status --json 2>/dev/null || echo "not connected"
echo ""
echo "=== STEP: start a watched Session (workers only) ==="
echo "Run this on EACH worker:"
echo "  sentinal watch -d -t \"acceptance-$(hostname)\" -- sh -lc 'echo READY on $(hostname); exec \${SHELL:-/bin/sh}'"
echo "Then note the Session ID printed."
echo ""
echo "=== STEP: list sessions ==="
sentinal ls --json 2>/dev/null | python3 -c "import sys,json; data=json.load(sys.stdin); [print(f\"  id={s['id']} title={s.get('title','')} state={s['state']} origin={s.get('origin','UI')}\") for s in (data if isinstance(data,list) else data.get('sessions',[]))]" 2>/dev/null || sentinal ls
echo ""
echo "=== STEP: disconnect test (run on Worker A only, later) ==="
echo "  sentinal disconnect"
echo "  # expect: Disconnected; Machine ID ... is kept"
echo "  # then on control UI: Machine shows 'Disconnected · last seen Ns ago'"
echo ""
echo "=== STEP: re-enroll (after disconnect, on Worker A) ==="
echo "  # In control PWA: Settings → Machines → Add Machine → copy the code"
echo "  sentinal connect https://<control>.<tailnet>.ts.net --name \"$(hostname)\""
echo "  # enter code at hidden prompt"
echo "  sentinal ls --json   # confirm no duplicate sessions"
echo ""
echo "=== 4.B: configure notifications (each worker) ==="
echo "mkdir -p ~/.config/terminal-agent"
echo "cat > ~/.config/terminal-agent/notify.toml <<'EOF'"
echo "server = \"https://ntfy.sh\""
echo "topic  = \"sentinal-<your-topic>\""
echo "# token = \"tk_...\"  (optional)"
echo "EOF"
echo "chmod 600 ~/.config/terminal-agent/notify.toml"
echo "Then restart the daemon:"
echo "  systemctl --user restart sentinald   # Linux"
echo "  launchctl kickstart -k gui/\$(id -u)/dev.sentinal.sentinald   # macOS"
echo ""
echo "=== 4.B: phone steps (at control origin https://<control>.<tailnet>.ts.net) ==="
echo "1. Sign in → Add to Home Screen → launch standalone"
echo "2. Home shows both workers Online"
echo "3. Attach to Worker A session, type: printf 'A-only-%s\\n' \$(date +%s)"
echo "   → confirm Worker B terminal did NOT change"
echo "4. Attach to Worker B, type: printf 'B-only-%s\\n' \$(date +%s)"
echo "5. Search history for 'A-only' → one-Machine filter shows only A's"
echo "6. Run Recipe 'cargo test' (or 'pytest') from Worker A catalog"
echo "   → new Session appears under Worker A only"
echo "7. Wait for it to finish → phone gets notification:"
echo "   '<Worker A> · cargo test: command finished with exit 0'"
echo "8. On Worker B, start: sentinal watch -- sh -lc 'read -p \"Continue? \" ans; echo got \$ans'"
echo "   → one 'waiting for input' push (no repeat within 5 min)"
echo "9. From a finished Command, 'Save as Recipe' → appears only in that Machine's catalog"
echo "10. DevTools → Application → Storage: no tokens, no worker credentials"
echo ""
echo "=== Credential sweep (each Machine) ==="
echo "  TOKEN=\$(cat ~/.config/terminal-agent/token 2>/dev/null)"
echo "  grep -r \"\$TOKEN\" ~/.config/terminal-agent/recipes/ ~/.config/terminal-agent/notification-rules.json 2>/dev/null && echo 'LEAK FOUND' || echo 'clean: no token in recipes/rules'"
